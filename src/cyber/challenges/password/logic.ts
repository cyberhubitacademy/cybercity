/* ---------------- Grading ---------------- */

export interface PasswordAnswers {
  ranking: string[];
  flagged: string[];
  attackType: AttackType | null;
  controls: string[];
  statements: Record<string, HashOrEnc | undefined>;
  algorithm: string | null;
}

export function emptyPasswordAnswers(): PasswordAnswers {
  return { ranking: SAMPLE_PASSWORDS.map((p) => p.id), flagged: [], attackType: null, controls: [], statements: {}, algorithm: null };
}

export interface PasswordGrade {
  score: number;
  passed: boolean;
  breakdown: ScoreLine[];
  rankingAcc: number;
  foundCompromise: boolean;
  falseFlags: number;
  attackCorrect: boolean;
  controlsGood: string[];
  controlsBad: string[];
  controlsMissed: string[];
  statementsCorrect: number;
  algorithmCorrect: boolean;
  mistakes: string[];
}

export function gradePassword(a: PasswordAnswers, passScore: number): PasswordGrade {
  const mistakes: string[] = [];
  const log = buildLoginLog();
  const legitIds = new Set(log.filter((e) => e.sourceIp.startsWith('192.0.2.')).map((e) => e.id));

  // A: ranking (30)
  const rankingAcc = rankingAccuracy(a.ranking, correctRanking());
  const rankPts = Math.round(rankingAcc * 30);
  if (rankingAcc < 1) mistakes.push('Password ranking was off — length and true randomness beat clever substitutions and appended years.');

  // B: log review (35) = compromise flag 15 (minus false flags) + attack type 5 + controls 15
  const foundCompromise = a.flagged.includes(COMPROMISE_EVENT_ID);
  const falseFlags = a.flagged.filter((id) => legitIds.has(id)).length;
  const flagPts = Math.max(0, (foundCompromise ? 15 : 0) - falseFlags * 5);
  if (!foundCompromise) mistakes.push('Missed the 03:12 successful login for carla from the same hosting-provider range that was spraying other accounts.');
  if (falseFlags) mistakes.push(`Flagged ${falseFlags} normal login(s) from the café network as malicious.`);
  const attackCorrect = a.attackType === 'stuffing';
  if (!attackCorrect) mistakes.push('Many usernames, one or two tries each, from automated clients = credential stuffing, not brute force.');
  const goodIds = CONTROLS.filter((c) => c.good).map((c) => c.id);
  const controlsGood = a.controls.filter((c) => goodIds.includes(c));
  const controlsBad = a.controls.filter((c) => !goodIds.includes(c));
  const controlsMissed = goodIds.filter((c) => !a.controls.includes(c));
  const ctrlPts = Math.max(0, Math.round((controlsGood.length / goodIds.length) * 15 - controlsBad.length * 4));
  for (const id of controlsBad) {
    const c = CONTROLS.find((x) => x.id === id);
    if (c) mistakes.push(`Chose "${c.label}" — ${c.explain}`);
  }
  const logPts = flagPts + (attackCorrect ? 5 : 0) + ctrlPts;

  // C: hashing (35) = statements 25 + algorithm 10
  const statementsCorrect = STATEMENTS.filter((s) => a.statements[s.id] === s.answer).length;
  const algorithmCorrect = ALGORITHMS.find((x) => x.id === a.algorithm)?.good ?? false;
  if (statementsCorrect < STATEMENTS.length) mistakes.push('Mixed up hashing (one-way, for checking) and encryption (reversible, for reading later).');
  if (!algorithmCorrect) mistakes.push('Password storage needs a slow salted hash like Argon2id or bcrypt.');
  const hashPts = Math.round((statementsCorrect / STATEMENTS.length) * 25) + (algorithmCorrect ? 10 : 0);

  const score = clampScore(rankPts + logPts + hashPts);
  return {
    score,
    passed: score >= passScore,
    breakdown: [
      { label: 'Strength lab ranking', value: rankPts, max: 30 },
      { label: 'Login log investigation', value: logPts, max: 35 },
      { label: 'Hashing vs encryption', value: hashPts, max: 35 },
    ],
    rankingAcc,
    foundCompromise,
    falseFlags,
    attackCorrect,
    controlsGood,
    controlsBad,
    controlsMissed,
    statementsCorrect,
    algorithmCorrect,
    mistakes,
  };
}

export function toPasswordResult(g: PasswordGrade, hintsUsed: number): ChallengeResult {
  return {
    challengeId: 'password-1',
    score: g.score,
    passed: g.passed,
    breakdown: g.breakdown,
    conceptsPracticed: ['identity-password-strength', 'identity-credential-stuffing', 'identity-mfa', 'identity-hashing-salting'],
    mistakes: g.mistakes,
    hintsUsed,
  };
}
