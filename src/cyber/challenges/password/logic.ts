/* ---------------- Stage C: hashing vs encryption ---------------- */

/** Toy 64-bit-ish hash built from two FNV-1a passes. EDUCATIONAL ONLY — not for real use. */
export function toyHash(input: string): string {
  const fnv = (s: string, seed: number): number => {
    let h = seed >>> 0;
    for (let i = 0; i < s.length; i++) {
      h ^= s.charCodeAt(i);
      h = Math.imul(h, 0x01000193) >>> 0;
    }
    return h >>> 0;
  };
  const a = fnv(input, 0x811c9dc5);
  const b = fnv(input + a.toString(16), 0x9747b28c);
  return a.toString(16).padStart(8, '0') + b.toString(16).padStart(8, '0');
}

export function saltedToyHash(salt: string, password: string): string {
  return toyHash(salt + ':' + password);
}

