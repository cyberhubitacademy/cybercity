/* ---------------- Stage A: strength estimation ---------------- */

/** Tiny stand-in for the huge breached-password and dictionary lists real estimators use. */
const COMMON_PASSWORDS = new Set(['password', 'password1', '123456', '12345678', 'qwerty', 'letmein', 'welcome', 'admin', 'iloveyou', 'sunshine']);
const DICTIONARY = [
  'password', 'summer', 'winter', 'spring', 'autumn', 'coral', 'cafe', 'welcome', 'admin', 'qwerty', 'neon', 'bay', 'love',
  'dragon', 'monkey', 'sunset', 'palm', 'beach', 'rico', 'carla', 'flamingo', 'falcon', 'radio', 'letmein', 'shadow', 'master',
];
const LEET: Record<string, string> = { '0': 'o', '1': 'l', '3': 'e', '4': 'a', '@': 'a', '$': 's', '5': 's', '7': 't' };
/** Size of the word list a passphrase generator draws from (Diceware). */
const DICEWARE_WORDS = 7776;

export interface StrengthReport {
  bits: number;
  label: 'Terrible' | 'Weak' | 'Fair' | 'Strong' | 'Excellent';
  reasons: string[];
}

function charsetSize(s: string): number {
  let n = 0;
  if (/[a-z]/.test(s)) n += 26;
  if (/[A-Z]/.test(s)) n += 26;
  if (/[0-9]/.test(s)) n += 10;
  if (/[^a-zA-Z0-9]/.test(s)) n += 33;
  return Math.max(n, 1);
}

function labelFor(bits: number): StrengthReport['label'] {
  if (bits < 20) return 'Terrible';
  if (bits < 36) return 'Weak';
  if (bits < 50) return 'Fair';
  if (bits < 70) return 'Strong';
  return 'Excellent';
}

/**
 * Pattern-aware entropy estimate (simplified zxcvbn idea): attackers try common passwords,
 * dictionary words (with leetspeak), years and digit runs first, so those parts add few bits.
 * Remaining random characters add log2(charset) bits each.
 */
export function estimateStrength(pw: string): StrengthReport {
  const reasons: string[] = [];
  if (pw.length === 0) return { bits: 0, label: 'Terrible', reasons: ['Empty.'] };
  if (COMMON_PASSWORDS.has(pw.toLowerCase())) {
    return { bits: 4, label: 'Terrible', reasons: ['On every "most common passwords" list — guessed in the first few tries.'] };
  }

  // Passphrase: 4+ lowercase words joined by separators.
  const words = pw.split(/[-_ .]/).filter(Boolean);
  if (words.length >= 4 && words.every((w) => /^[a-z]{3,}$/i.test(w))) {
    const bits = words.length * Math.log2(DICEWARE_WORDS);
    reasons.push(`${words.length} random words ≈ ${Math.log2(DICEWARE_WORDS).toFixed(1)} bits each from a ${DICEWARE_WORDS}-word list.`);
    reasons.push('Long and easy to remember — as long as the words are chosen randomly, not as a sentence about you.');
    return { bits: round1(bits), label: labelFor(bits), reasons };
  }

  let rest = pw;
  let bits = 0;
  const normalized = (s: string) => s.toLowerCase().replace(/[0134@$57]/g, (c) => LEET[c] ?? c);

  // Dictionary words (longest first), checked on the leet-normalized string.
  const sorted = [...DICTIONARY].sort((a, b) => b.length - a.length);
  let found = true;
  while (found) {
    found = false;
    const norm = normalized(rest);
    for (const w of sorted) {
      const i = norm.indexOf(w);
      if (i >= 0) {
        const original = rest.slice(i, i + w.length);
        bits += Math.log2(DICTIONARY.length * 400) + (/[A-Z]/.test(original) ? 1 : 0) + (original.toLowerCase() !== w ? 1 : 0);
        reasons.push(`Dictionary word "${original}" — tried early by cracking tools${original.toLowerCase() !== w ? ' (leetspeak doesn\'t fool them)' : ''}.`);
        rest = rest.slice(0, i) + rest.slice(i + w.length);
        found = true;
        break;
      }
    }
  }

  const year = /(19|20)\d\d/.exec(rest);
  if (year) {
    bits += 7;
    reasons.push(`Year "${year[0]}" — only ~120 likely values.`);
    rest = rest.replace(year[0], '');
  }
  const run = /(0123|1234|2345|123|321|111|000)/.exec(rest);
  if (run) {
    bits += 3;
    reasons.push(`Digit run "${run[0]}" — a classic suffix.`);
    rest = rest.replace(run[0], '');
  }

  if (rest.length > 0) {
    const b = rest.length * Math.log2(charsetSize(rest));
    bits += b;
    reasons.push(`${rest.length} unpredictable character(s) add ≈ ${b.toFixed(0)} bits.`);
  }
  if (pw.length < 12) reasons.push(`Only ${pw.length} characters — length is the cheapest strength you can buy.`);
  return { bits: round1(bits), label: labelFor(bits), reasons };
}

function round1(n: number): number {
  return Math.round(n * 10) / 10;
}

export interface SamplePassword {
  id: string;
  value: string;
  owner: string;
}

export const SAMPLE_PASSWORDS: SamplePassword[] = [
  { id: 'p-summer', value: 'Summer1985!', owner: 'Carla\'s old café password (reused everywhere)' },
  { id: 'p-manager', value: 'k7#Qm9!vRz2&Lp4X', owner: 'Generated by a password manager' },
  { id: 'p-common', value: 'password1', owner: 'The back-office PC' },
  { id: 'p-phrase', value: 'coral-sunset-falcon-radio', owner: 'Luis\'s random 4-word passphrase' },
  { id: 'p-random10', value: 'Wq8#pLz2!m', owner: 'Jo\'s random 10-character password' },
];

/** Correct ranking, weakest → strongest, derived from the estimator. */
export function correctRanking(samples: SamplePassword[] = SAMPLE_PASSWORDS): string[] {
  return [...samples].sort((a, b) => estimateStrength(a.value).bits - estimateStrength(b.value).bits).map((s) => s.id);
}

/** Fraction of pairs in the right relative order (Kendall-tau style), 0..1. */
export function rankingAccuracy(order: string[], correct: string[]): number {
  const pos = new Map(order.map((id, i) => [id, i]));
  let good = 0;
  let total = 0;
  for (let i = 0; i < correct.length; i++) {
    for (let j = i + 1; j < correct.length; j++) {
      total++;
      const a = pos.get(correct[i]);
      const b = pos.get(correct[j]);
      if (a !== undefined && b !== undefined && a < b) good++;
    }
  }
  return total === 0 ? 0 : good / total;
}

/* ---------------- Stage B: login log review ---------------- */

export interface LoginEvent {
  id: string;
  time: string;
  user: string;
  sourceIp: string;
  location: string;
  result: 'FAIL' | 'SUCCESS';
  device: string;
}

export function buildLoginLog(): LoginEvent[] {
  const log: LoginEvent[] = [
    { id: 'e01', time: '09:01:12', user: 'carla', sourceIp: '192.0.2.10', location: 'Neon Bay', result: 'SUCCESS', device: 'Café laptop' },
    { id: 'e02', time: '13:40:03', user: 'luis', sourceIp: '192.0.2.11', location: 'Neon Bay', result: 'FAIL', device: 'Front tablet' },
    { id: 'e03', time: '13:40:21', user: 'luis', sourceIp: '192.0.2.11', location: 'Neon Bay', result: 'SUCCESS', device: 'Front tablet' },
  ];
  const users = ['admin', 'ana', 'jo', 'info', 'carla', 'orders', 'luis', 'manager', 'test', 'billing', 'carla.reyes', 'owner'];
  users.forEach((u, i) => {
    const sec = String(5 + i * 4).padStart(2, '0');
    log.push({
      id: `s${String(i).padStart(2, '0')}`,
      time: `03:0${Math.min(9, Math.floor(i / 2) + 4)}:${sec}`,
      user: u,
      sourceIp: `198.51.100.${23 + (i % 5) * 11}`,
      location: 'Unknown (hosting provider)',
      result: 'FAIL',
      device: 'python-requests/2.x',
    });
  });
  log.push({ id: 'e-pwn', time: '03:12:40', user: 'carla', sourceIp: '198.51.100.23', location: 'Unknown (hosting provider)', result: 'SUCCESS', device: 'python-requests/2.x' });
  log.push({ id: 'e04', time: '03:14:02', user: 'orders', sourceIp: '198.51.100.67', location: 'Unknown (hosting provider)', result: 'FAIL', device: 'python-requests/2.x' });
  log.push({ id: 'e05', time: '08:55:30', user: 'ana', sourceIp: '192.0.2.14', location: 'Neon Bay', result: 'SUCCESS', device: 'Kitchen PC' });
  return log.sort((a, b) => a.time.localeCompare(b.time));
}

export const COMPROMISE_EVENT_ID = 'e-pwn';

/** Detector used for the "hint" and tests: success from a source that also produced failures across many accounts. */
export function detectStuffingSuccess(log: LoginEvent[]): string[] {
  const subnetOf = (ip: string) => ip.split('.').slice(0, 3).join('.');
  const usersPerSubnet = new Map<string, Set<string>>();
  for (const e of log) {
    if (e.result !== 'FAIL') continue;
    const s = subnetOf(e.sourceIp);
    if (!usersPerSubnet.has(s)) usersPerSubnet.set(s, new Set());
    usersPerSubnet.get(s)?.add(e.user);
  }
  return log.filter((e) => e.result === 'SUCCESS' && (usersPerSubnet.get(subnetOf(e.sourceIp))?.size ?? 0) >= 5).map((e) => e.id);
}

